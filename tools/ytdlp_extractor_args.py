"""Generate the extractor arguments yt-dlp reads, key by key (`T-255`, `ARC-010` amended 2026-10-19,
fourth).

**Why generated.** `--extractor-args` takes `KEY:ARG=VALUE` pairs, and yt-dlp ignores a pair no
code reads, which is `T012-R5`'s *accepted and silently dropped*. No extractor declares its
argument names, and the keys are not the extractor list: `twitch`, `youtube-ejs` and
`youtubepot-webpo` are read and are not extractors. So the pairs are read **from the pinned
source**, every call that reads one, and written into a module `core/` can import, since it may not
import yt-dlp. `tests/unit/test_extractor_args.py` regenerates it and compares.

    python tools/ytdlp_extractor_args.py            # rewrite the module
    python tools/ytdlp_extractor_args.py --check    # exit 1 if it is out of date

**What is read, and how.** Each `_configuration_arg('ARG', ...)` call in yt-dlp's extractors, by
its syntax tree: the key is the `ie_key` it names, or, where it names none, the key of every real
extractor the enclosing class's method can run for. A YouTube token or solver provider reads its
settings under `youtubepot-NAME` or `youtubejsc-NAME`, and the solver itself reads `youtube-ejs`
through `ejs_setting`. **A read this cannot resolve stops the generator**, unless `STATED` below
answers it by hand, so a new reading in a later yt-dlp is classified rather than missed.
"""

from __future__ import annotations

import argparse
import ast
import importlib
import sys
from collections.abc import Callable, Iterator
from pathlib import Path
from typing import Any, Final

ROOT: Final = Path(__file__).resolve().parent.parent
TARGET: Final = ROOT / "src" / "tracks_and_trails" / "core" / "extractor_arg_table.py"

#: Reads whose argument is not written out, answered by hand: module, enclosing class and the
#: variable the argument is in, to the arguments it can be. **Each is read from the class rather
#: than copied**, where the names live in one of its attributes, so a renamed one follows the pin.
STATED: Final[dict[tuple[str, str, str], Callable[[Any], Iterator[str]]]] = {
    # `for key, prefix in self._IGNORE_MAP.items()`
    ("yt_dlp.extractor.hotstar", "HotStarIE", "key"): lambda cls: iter(cls._IGNORE_MAP),
    # `for key, default in self._APP_INFO_DEFAULTS.items() if key != 'iid'`
    ("yt_dlp.extractor.tiktok", "TikTokBaseIE", "key"): lambda cls: (
        key for key in cls._APP_INFO_DEFAULTS if key != "iid"
    ),
    # `get_single_config_arg = lambda c: self._configuration_arg(c, [''])[0]`, called once, with
    # `'comment_sort'`, in the same method.
    ("yt_dlp.extractor.youtube._video", "YoutubeIE", "c"): lambda _cls: iter(("comment_sort",)),
}

#: The families of YouTube's content providers, by the module their base class is in, and the
#: prefix each reads its settings under (`EXTRACTOR_ARG_PREFIX` in each director).
PROVIDER_PREFIXES: Final = {
    "yt_dlp.extractor.youtube.pot": "youtubepot",
    "yt_dlp.extractor.youtube.jsc": "youtubejsc",
}

HEADER: Final = '''"""Every extractor argument yt-dlp reads, by key. **Generated.**

Do not edit this file. It is written by `tools/ytdlp_extractor_args.py` from the pinned yt-dlp's
source, and `tests/unit/test_extractor_args.py` regenerates it and compares (`T-255`, `ARC-010`
amended 2026-10-19, fourth). A pair absent here is one no code at the pin reads, and is refused.
"""

from __future__ import annotations

from typing import Final

#: The yt-dlp release this was read from.
READ_FROM: Final = "{version}"

#: Key -> every argument read under it. Keys and arguments are lower case, as yt-dlp's parser makes
#: them; an argument's `-` is read as `_`.
EXTRACTOR_ARGS: Final[dict[str, frozenset[str]]] = {{
{rows}}}
'''


def _real_extractors() -> set[str]:
    from yt_dlp.extractor import gen_extractor_classes

    return {cls.__name__ for cls in gen_extractor_classes()}


def _keys_below(cls: Any, real: set[str]) -> set[str]:
    """The key of `cls` and every real extractor under it, which an unnamed `ie_key` resolves to."""
    found: set[str] = set()
    seen: set[Any] = set()
    stack = [cls]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        if current.__name__ in real:
            found.add(current.ie_key().lower())
        stack.extend(current.__subclasses__())
    return found


def _provider_key(module_name: str, cls: Any) -> str | None:
    for prefix_module, prefix in PROVIDER_PREFIXES.items():
        if module_name.startswith(prefix_module):
            return f"{prefix}-{cls.PROVIDER_KEY.lower()}"
    return None


def read_pairs() -> tuple[dict[str, set[str]], list[str]]:
    """Every `(key, argument)` read at the pin, and every read that could not be resolved."""
    import yt_dlp

    package = Path(yt_dlp.__file__).parent
    real = _real_extractors()
    pairs: dict[str, set[str]] = {}
    unresolved: list[str] = []
    for path in sorted(package.rglob("*.py")):
        text = path.read_text(encoding="utf-8")
        if "_configuration_arg(" not in text and "ejs_setting(" not in text:
            continue
        module_name = ".".join(path.relative_to(package.parent).with_suffix("").parts)
        reader = _Reader(importlib.import_module(module_name), module_name, real, pairs, unresolved)
        reader.visit(ast.parse(text))
    return pairs, unresolved


class _Reader(ast.NodeVisitor):
    """One module's reads of extractor arguments, added to `pairs` or to `unresolved`."""

    def __init__(
        self,
        module: Any,
        module_name: str,
        real: set[str],
        pairs: dict[str, set[str]],
        unresolved: list[str],
    ) -> None:
        self.module = module
        self.module_name = module_name
        self.real = real
        self.pairs = pairs
        self.unresolved = unresolved
        self.classes: list[str] = []

    def add(self, key: str, argument: str) -> None:
        self.pairs.setdefault(key.lower(), set()).add(argument.lower().replace("-", "_"))

    # `ast.NodeVisitor`'s names, hence the camelCase.
    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        self.classes.append(node.name)
        self.generic_visit(node)
        self.classes.pop()

    def visit_Call(self, node: ast.Call) -> None:
        self.generic_visit(node)
        func = node.func
        if not isinstance(func, ast.Attribute) or not node.args:
            return
        where = f"{self.module_name}:{node.lineno}"
        first = node.args[0]
        if func.attr == "ejs_setting":
            if isinstance(first, ast.Constant) and isinstance(first.value, str):
                self.add("youtube-ejs", first.value)
            else:
                self.unresolved.append(f"{where}: ejs_setting({ast.unparse(first)})")
            return
        if func.attr != "_configuration_arg":
            return
        enclosing = self.classes[-1] if self.classes else ""
        owner = getattr(self.module, enclosing, None) if enclosing else None
        if isinstance(first, ast.Constant) and isinstance(first.value, str):
            arguments: list[str] = [first.value]
        else:
            stated = STATED.get((self.module_name, enclosing, ast.unparse(first)))
            if stated is None or owner is None:
                self.unresolved.append(f"{where}: an argument named by {ast.unparse(first)}")
                return
            arguments = list(stated(owner))
        named = next((k.value for k in node.keywords if k.arg == "ie_key"), None)
        for key in _keys_of(
            named, self.module, owner, self.module_name, self.real, where, self.unresolved
        ):
            for argument in arguments:
                self.add(key, argument)


def _keys_of(
    named: ast.expr | None,
    module: Any,
    owner: Any,
    module_name: str,
    real: set[str],
    where: str,
    unresolved: list[str],
) -> set[str]:
    """The keys a read is made under, from its `ie_key` or from where it is made."""
    if named is None:
        if owner is None:
            unresolved.append(f"{where}: no key and no class")
            return set()
        provider = _provider_key(module_name, owner) if hasattr(owner, "PROVIDER_KEY") else None
        if provider is not None:
            return {provider}
        keys = _keys_below(owner, real)
        if not keys:
            unresolved.append(f"{where}: no real extractor below {owner.__name__}")
        return keys
    try:
        if isinstance(named, ast.Constant) and isinstance(named.value, str):
            return {named.value.lower()}
        if isinstance(named, ast.Name):
            value = getattr(module, named.id)
            return {(value if isinstance(value, str) else value.ie_key()).lower()}
        if (
            isinstance(named, ast.Call)
            and isinstance(named.func, ast.Attribute)
            and named.func.attr == "ie_key"
            and isinstance(named.func.value, ast.Name)
        ):
            return {getattr(module, named.func.value.id).ie_key().lower()}
        if (
            isinstance(named, ast.Attribute)
            and isinstance(named.value, ast.Name)
            and named.value.id == "self"
            and owner is not None
        ):
            return {str(getattr(owner, named.attr)).lower()}
    except AttributeError as error:
        unresolved.append(f"{where}: ie_key {ast.unparse(named)} ({error})")
        return set()
    unresolved.append(f"{where}: ie_key {ast.unparse(named)}")
    return set()


def rendered() -> str:
    import yt_dlp

    pairs, unresolved = read_pairs()
    if unresolved:
        raise SystemExit(
            "these reads of extractor arguments could not be resolved; answer each in STATED:\n"
            + "\n".join(unresolved)
        )
    rows = "".join(_row(key, sorted(arguments)) for key, arguments in sorted(pairs.items()))
    return HEADER.format(version=yt_dlp.version.__version__, rows=rows)


def _row(key: str, arguments: list[str]) -> str:
    """One key's row, laid out as `ruff format` lays it out, so the module passes the gate."""
    quoted = [f'"{argument}"' for argument in arguments]
    inline = f'    "{key}": frozenset({{{", ".join(quoted)}}}),\n'
    if len(inline) <= 101:
        return inline
    inner = "".join(f"            {argument},\n" for argument in quoted)
    return f'    "{key}": frozenset(\n        {{\n{inner}        }}\n    ),\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is out of date")
    arguments = parser.parse_args(argv)
    text = rendered()
    if arguments.check:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run {Path(__file__).name}")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
