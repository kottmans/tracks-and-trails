def audit_rows() -> list[tuple[tuple[str, ...], str, str]]:
    """The classification tables only. The findings above them have tables of their own."""
    text = AUDIT.read_text(encoding="utf-8")
    _, _, tables = text.partition("\n## The tables\n")
    if not tables:
        raise SystemExit("the audit has no '## The tables' section to read")
    found = []
    for line in tables.splitlines():
        match = _ROW.match(line.strip())
        if match:
            spellings = tuple(re.findall(r"`([^`]+)`", match.group(1)))
            found.append((spellings, match.group(2), match.group(3)))
    return found


def built_typed_options() -> dict[str, str]:
    """The typed options that already have a `DownloadRequest` or `Preset` field, from the audit.

    **Stated rather than inferred**, which is `T183-R4`'s correction: deriving "built" from what
    the nine typed tasks did not claim is circular, and swapping a built option for an unbuilt one
    kept every count intact. The hatch needs this because a typed option **with** a control is
    refused — `ARC-010` gives the visible control the win — while one still waiting for its task is
    permitted, and only this table separates them.
    """
    text = AUDIT.read_text(encoding="utf-8")
    header = text.index("| Option | `DownloadRequest` or `Preset` field |")
    table = text[header : text.index("\n\n", header)]
    return {
        found.group(1): found.group(2)
        for line in table.split("\n")[2:]
        if (found := re.match(r"^\| `([^`]+)` \| `([^`]+)` \|$", line.strip()))
    }


def built_spellings() -> dict[str, str]:
    """Every spelling of every option the audit's built table names, each mapped to its field.

    **`T-361`.** The built table names one spelling per option, and the hatch refuses by the
    spelling typed, so `--limit-rate`, the same parser option as the listed `-r`, was admitted; and
    `derive_destinations` skips a built option, so the hatch then produced nothing for it, which is
    `REQ-031`'s *accepted and silently dropped*. The aliases are read from yt-dlp's parser rather
    than listed, so a new typed field brings all of them with it.

    **Aliases only, and not every option sharing a destination is one** (`T-250`, which corrected
    this): `--format-sort-reset` and `--check-all-formats` are other parser options setting the
    destinations of `-S` and `--check-formats`. Each needs its own row in the built table, which is
    what moved them from `hatch` to `typed`, and the audit's drift test fails on any such option
    left reachable.
    """
    from yt_dlp.options import create_parser

    parser = create_parser()
    by_spelling = {
        spelling: option
        for group in parser.option_groups
        for option in group.option_list
        for spelling in _spellings(option)
    }
    found: dict[str, str] = {}
    for spelling, field in built_typed_options().items():
        option = by_spelling.get(spelling)
        if option is None:
            raise SystemExit(f"the audit's built table names {spelling}, which the parser lacks")
        for alias in _spellings(option):
            found[alias] = field
    return found


def parser_arity() -> dict[str, int]:
    """Every spelling yt-dlp's parser knows, and how many values each consumes.

    **Generated rather than read at runtime**, and that is an architecture rule rather than a
    preference: `tests/unit/test_layering.py` confines `yt_dlp` imports to `worker.py` and
    `ytdlp_adapter.py`, so upstream churn stays absorbable (`NFR-008`). Pinning the table here
    means the hatch can decide what a user typed **without importing yt-dlp at all**, and the
    version test fails if the installed release ever stops matching the pin.

    `create_parser()` builds the option table and returns; none of `parse_options`' side effects
    happen, which is what makes this safe to run at all.
    """
    from yt_dlp.options import create_parser

    parser = create_parser()
    arity: dict[str, int] = {}
    for group in parser.option_groups:
        for option in group.option_list:
            takes = option.nargs if option.takes_value() else 0
            for spelling in tuple(option._short_opts) + tuple(option._long_opts):
                arity[spelling] = takes or 0
    return arity


#: Values tried in order until a pair of them parses and shows a difference.
#:
#: **Two values of the same option, never a value against the defaults** (`T184-R1`). Diffing an
#: option against an empty argv is blind whenever the value a user typed *is* the default:
#: `--fragment-retries 10` produces exactly the default dictionary, the diff is empty, and the key
#: is then absent — which yt-dlp's `RetryManager` reads as **zero** retries. Comparing two values
#: of the option finds the destination whatever the defaults happen to be.
#:
#: The list is a ladder rather than a type map because yt-dlp declares many numeric and format
#: options as strings and validates them itself, so `option.type` does not say what is acceptable.
_LADDER: Final = (
    ("1", "2"),
    ("x", "y"),
    ("1K", "2K"),
    ("20200101", "20200102"),
    ("mp4", "mkv"),
    ("srt", "vtt"),
    ("jpg", "png"),
    ("sponsor", "selfpromo"),
    ("youtube-dl", "filename"),
    ("en", "de"),
    ("1s", "2s"),
    ("title:x", "title:y"),
    ("key=1", "key=2"),
    ("1:2", "3:4"),
    ("infinite", "3"),
    ("5", "6"),
)


def _quietly(argv: list[str]) -> dict[str, object]:
    """`parse_options`, with its usage text kept out of this program's own output."""
    from yt_dlp import parse_options

    with contextlib.redirect_stderr(io.StringIO()), contextlib.redirect_stdout(io.StringIO()):
        return dict(parse_options(argv).ydl_opts)


def _spellings(option: object) -> tuple[str, ...]:
    return tuple(option._short_opts) + tuple(option._long_opts)  # type: ignore[attr-defined]


def _canonical(option: object) -> str:
    return (option._long_opts or option._short_opts)[0]  # type: ignore[attr-defined]


def _candidate_pairs(option: object, known: dict[str, object]) -> list[tuple[list[str], list[str]]]:
    """Argv pairs differing only in this option, best first."""
    spelling = _canonical(option)
    tried: list[tuple[list[str], list[str]]] = []
    if not option.takes_value():  # type: ignore[attr-defined]
        negation = "--no-" + spelling.removeprefix("--")
        plain = "--" + spelling.removeprefix("--no-")
        if negation in known:
            tried.append(([spelling], [negation]))
        if spelling.startswith("--no-") and plain in known and not known[plain].takes_value():  # type: ignore[attr-defined]
            tried.append(([spelling], [plain]))
        # Against nothing at all, which is the only pair available to a flag with no counterpart.
        tried.append(([spelling], []))
        return tried

    count = max(1, option.nargs or 1)  # type: ignore[attr-defined]
    choices = option.choices  # type: ignore[attr-defined]
    if option.type == "choice" and choices and len(choices) > 1:  # type: ignore[attr-defined]
        tried.append(([spelling, *[choices[0]] * count], [spelling, *[choices[1]] * count]))
    tried.extend(
        ([spelling, *[first] * count], [spelling, *[second] * count]) for first, second in _LADDER
    )
    return tried


def _measured(option: object, known: dict[str, object]) -> tuple[list[str], bool]:
    """The keys `option` changes, and whether any pair of its values could be parsed at all."""
    parsed = False
    for first, second in _candidate_pairs(option, known):
        try:
            before, after = _quietly(first), _quietly(second)
        except BaseException:  # noqa: S112 - a value this pair cannot supply; try the next
            # `BaseException`, because `optparse` raises `SystemExit` for a bad value as readily
            # as it raises an error, and a probe that let that through would take the generator
            # with it. An unusable pair is the expected case.
            continue
        parsed = True
        keys = sorted(k for k in set(before) | set(after) if before.get(k) != after.get(k))
        if keys:
            return keys, True
    return [], parsed


def _keys_of(spellings: set[str]) -> set[str]:
    """Every key the options with these spellings change, measured as `_measured` measures."""
    from yt_dlp.options import create_parser

    parser = create_parser()
    options = [option for group in parser.option_groups for option in group.option_list]
    known = {spelling: option for option in options for spelling in _spellings(option)}
    found: set[str] = set()
    for option in options:
        if set(_spellings(option)) & spellings:
            found.update(_measured(option, known)[0])
    return found


#: yt-dlp's own prefix for a compatibility value that switches a safety check off (`T-363`).
_UNSAFE_PREFIX: Final = "allow-unsafe-"

#: The audit's table of what each admitted compatibility value does here, and one of its rows.
_COMPAT_HEADER: Final = "| Value | Here | Why |"
_COMPAT_ROW: Final = re.compile(r"^\| `([a-z0-9-]+)` \| `(effect|inert)` \| (.+?) \|$")


def compat_rulings() -> dict[str, str]:
    """Each admitted compatibility value, `effect` or `inert`, from the audit (`T363-R2`).

    **Stated rather than derived**, for `NO_OBSERVABLE_EFFECT`'s reason: most values act at run
    time through `compat_opts`, where a parse sees nothing, so whether one does anything here is a
    reading of yt-dlp against what this application reaches, written down with its reason.
    """
    text = AUDIT.read_text(encoding="utf-8")
    header = text.index(_COMPAT_HEADER)
    table = text[header : text.index("\n\n", header)]
    return {
        found.group(1): found.group(2)
        for line in table.split("\n")[2:]
        if (found := _COMPAT_ROW.match(line.strip()))
    }


def read_by_yt_dlp(value: str) -> bool:
    """Whether any of yt-dlp's own code reads compatibility `value`, beyond the parser's list."""
    import yt_dlp

    package = Path(yt_dlp.__file__).parent
    quoted = (f"'{value}'", f'"{value}"')
    return any(
        spelling in path.read_text(encoding="utf-8")
        for path in package.rglob("*.py")
        if path != package / "options.py"
        for spelling in quoted
    )


def compat_values() -> tuple[dict[str, str | None], dict[str, tuple[str, ...]], tuple[str, ...]]:
    """Each `--compat-options` value's verdict, the aliases, and the keys an admitted one carries.

    **Each value parsed alone, and the process put back after it** (`T-363`). yt-dlp's
    `validate_options` switches its unsafe-extension check off for the whole process when it reads
    `allow-unsafe-ext`, and `set_compat_opts` rewrites the default format order for
    `prefer-vp9-sort`; both are restored here so one value's parse cannot colour the next.

    **A value the parse admits is then looked up in the audit** (`T363-R2`), which says whether it
    does anything here. One with no row stops the generator, so a value a new yt-dlp brings is
    classified rather than admitted by default; so does one called `effect` that nothing in yt-dlp
    reads and whose parse changes no key. An `inert` value still carries its keys, for a bundle
    that brings it along.
    """
    from yt_dlp.options import create_parser
    from yt_dlp.utils import FormatSorter
    from yt_dlp.utils._utils import _UnsafeExtensionError

    option = create_parser().get_option("--compat-options")
    arguments = option.callback_kwargs  # type: ignore[union-attr]
    allowed = sorted(arguments["allowed_values"])
    aliases = {name: tuple(items) for name, items in sorted(arguments["aliases"].items())}

    rows = audit_rows()
    controlled = _keys_of(set(built_spellings()))
    owned = _keys_of(
        {spelling for spellings, group, _ in rows if group == "app:sets" for spelling in spellings}
    )
    nothing = _quietly([])
    rulings = compat_rulings()
    unknown = sorted(set(rulings) - set(allowed))
    if unknown:
        raise SystemExit(f"the audit classifies compatibility values yt-dlp lacks: {unknown}")
    verdicts: dict[str, str | None] = {}
    carried: set[str] = set()
    for value in allowed:
        kept = (FormatSorter.default, _UnsafeExtensionError._enabled)
        try:
            parsed = _quietly(["--compat-options", value])
            unsafe = not _UnsafeExtensionError._enabled
        finally:
            FormatSorter.default, _UnsafeExtensionError._enabled = kept
        keys = {
            key
            for key in set(nothing) | set(parsed)
            if key != "compat_opts"
            and not key.startswith("_")
            and nothing.get(key) != parsed.get(key)
        }
        if value.startswith(_UNSAFE_PREFIX) or unsafe:
            verdicts[value] = "safety"
        elif keys & owned:
            # **Before `control`**: a key this application sets itself overrides any route to it.
            # `outtmpl` is both — `--embed-thumbnail` blanks the playlist thumbnail's template as
            # it parses — and `filename` would otherwise be sent to a setting that cannot do it.
            verdicts[value] = "app"
        elif keys & controlled:
            verdicts[value] = "control"
        else:
            ruling = rulings.get(value)
            if ruling is None:
                raise SystemExit(
                    f"--compat-options {value} is admitted and the audit does not say whether it "
                    f"does anything here; add its row under {_COMPAT_HEADER!r}"
                )
            if ruling == "effect" and not keys and not read_by_yt_dlp(value):
                raise SystemExit(
                    f"the audit says --compat-options {value} has an effect, but nothing in yt-dlp "
                    "reads it and its parse changes no key"
                )
            verdicts[value] = "inert" if ruling == "inert" else None
            carried |= keys
    return verdicts, aliases, ("compat_opts", *sorted(carried))


def derive_destinations() -> tuple[dict[str, tuple[str, ...]], list[str], list[str]]:
    """What each admitted option changes in the option dictionary, measured rather than assumed.

    Returns the destinations per spelling, the options that change nothing observable at this pin,
    and the options no value here can exercise. The maintainer ruled on 2026-09-20 that the last
    two are **refused**, each with the reason it is refused: an option that cannot be shown to
    reach yt-dlp must not be accepted and then quietly do nothing.
    """
    from yt_dlp.options import create_parser

    parser = create_parser()
    options = [option for group in parser.option_groups for option in group.option_list]
    known = {spelling: option for option in options for spelling in _spellings(option)}

    classes = {spelling: group for spellings, group, _ in audit_rows() for spelling in spellings}
    built = set(built_spellings())

    destinations: dict[str, tuple[str, ...]] = {}
    inert: list[str] = []
    unknown: list[str] = []
    for option in options:
        spellings = _spellings(option)
        group = classes.get(_canonical(option))
        if group not in _ADMITTED or any(spelling in built for spelling in spellings):
            continue
        # The pairs that never parse are reported by name as `EFFECT_UNKNOWN`.
        keys, parsed = _measured(option, known)
        if keys:
            for spelling in spellings:
                destinations[spelling] = tuple(keys)
        elif parsed:
            inert.extend(spellings)
        else:
            unknown.extend(spellings)
    return destinations, sorted(inert), sorted(unknown)


