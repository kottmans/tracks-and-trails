def postprocessor_order() -> list[str]:
    """The order yt-dlp itself puts postprocessors in (`T184-R10`).

    **Derived, because appending is wrong and guessing is worse.** Composing the hatch's chain
    after the application's put `FFmpegMetadata` before `ModifyChapters`, so `--remove-chapters`
    produced a file with no chapters at all — the metadata was written from the chapters, and then
    the chapters were removed. yt-dlp's own builder emits them in dependency order; this reads
    that order rather than reasoning about it.
    """
    from yt_dlp import parse_options

    with contextlib.redirect_stderr(io.StringIO()), contextlib.redirect_stdout(io.StringIO()):
        parsed = parse_options(list(_EVERY_PROCESSOR))
    return [str(spec["key"]) for spec in parsed.ydl_opts.get("postprocessors", [])]


def audit_version() -> str:
    stated = re.search(r"\*\*yt-dlp version:\*\* \*\*([0-9.]+)\*\*", AUDIT.read_text("utf-8"))
    if stated is None:
        raise SystemExit("the audit does not state the yt-dlp version it was taken against")
    return stated.group(1)


#: Ruff's limit for this repository. The generated file goes through the same gates as anything
#: written by hand, so an entry that would overrun it is wrapped here rather than excused there.
_WIDTH: Final = 100


def _entry(spelling: str, group: str, reason: str) -> str:
    """One `"spelling": ("class", "reason"),` line, wrapped when it will not fit.

    The audit's longest reason is over 200 characters, and no formatter splits a string literal,
    so a long one is emitted as implicit concatenation. `ruff format` leaves those alone, which is
    what makes the generated file stable under `--check`.
    """
    flat = f"    {spelling!r}: ({group!r}, {reason!r}),"
    if len(flat) <= _WIDTH:
        return flat + "\n"

    room = _WIDTH - 8 - 3  # eight spaces of indent, two quotes and a trailing space
    chunks: list[str] = []
    rest = reason
    while len(rest) > room:
        cut = rest.rfind(" ", 0, room)
        cut = cut if cut > 0 else room
        chunks.append(rest[: cut + 1])
        rest = rest[cut + 1 :]
    chunks.append(rest)

    body = "".join(f"        {chunk!r}\n" for chunk in chunks)
    return f"    {spelling!r}: (\n        {group!r},\n{body}    ),\n"


def rendered() -> str:
    """The module text, with one entry per spelling rather than per row."""
    lines = []
    for spellings, group, reason in sorted(audit_rows()):
        for spelling in spellings:
            lines.append(_entry(spelling, group, reason))
    built = "".join(
        f"    {spelling!r}: {field!r},\n" for spelling, field in sorted(built_spellings().items())
    )
    arity = "".join(
        f"    {spelling!r}: {takes!r},\n" for spelling, takes in sorted(parser_arity().items())
    )
    destinations, inert, unknown = derive_destinations()
    verdicts, aliases, carried = compat_values()
    # **`--compat-options` carries what its admitted values change** (`T-363`), measured value by
    # value. Two values of one option, the measure every other option gets, found the keys that
    # `youtube-dl` and `filename` differ in, which left out `multistreams`' two: admitted, and then
    # dropped by the merge.
    destinations["--compat-options"] = carried
    keys = "".join(
        f"    {spelling!r}: {found!r},\n" for spelling, found in sorted(destinations.items())
    )
    return _formatted(
        _HEADER.format(
            version=audit_version(),
            rows="".join(lines),
            built=built,
            arity=arity,
            keys=keys,
            inert="".join(f"        {spelling!r},\n" for spelling in inert),
            unknown="".join(f"        {spelling!r},\n" for spelling in unknown),
            compat="".join(f"    {value!r}: {verdict!r},\n" for value, verdict in verdicts.items()),
            compat_aliases="".join(
                f"    {name!r}: {items!r},\n" for name, items in aliases.items()
            ),
            order="".join(
                f"    {key!r}: {rank},\n" for rank, key in enumerate(postprocessor_order())
            ),
        )
    )


def _formatted(text: str) -> str:
    """`text` as `ruff format` would write it, so the gate and the generator cannot disagree.

    **The pipe is UTF-8 by name** (`T-356`). Ruff reads stdin as UTF-8; text mode left to itself
    writes the locale's encoding, which is cp1252 on Windows, and the module's em dashes then
    arrive as bytes Ruff refuses.
    """
    formatted = subprocess.run(  # noqa: S603 - a fixed argv, and ruff is this repo's formatter
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(TARGET), "-"],
        input=text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if formatted.returncode != 0:
        raise SystemExit(f"ruff format refused the generated module:\n{formatted.stderr}")
    return formatted.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="say whether the module is up to date rather than rewriting it",
    )
    arguments = parser.parse_args()

    wanted = rendered()
    if arguments.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current == wanted:
            print(f"{TARGET.relative_to(ROOT)} is up to date")
            return 0
        print(f"{TARGET.relative_to(ROOT)} is out of date; run this tool without --check")
        return 1

    TARGET.write_text(wanted, encoding="utf-8")
    entries = len(audit_rows())
    print(f"wrote {TARGET.relative_to(ROOT)} from {entries} audit rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
